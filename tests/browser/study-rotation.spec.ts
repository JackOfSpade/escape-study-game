import { expect, test, type Page } from "@playwright/test";
import {
  enterNativeGame,
  flushNativeSave,
  mockClaudeStudy,
} from "./study-harness";

/** Walk to an untouched physical station, open it and report its issued track. */
async function openUntouched(page: Page) {
  // E toggles: leave the finished question's terminal before walking on.
  if (await page.locator("#terminal").isVisible()) {
    await page.locator("#leave").click();
    await expect(page.locator("#terminal")).toBeHidden();
  }
  // Some stations sit beside a partition that E would grip first; skip those.
  for (let skip = 0; ; skip++) {
    const id = await page.evaluate((skip) => {
      const d = (window as any).__deadAir,
        g = d.game;
      // Stations in one room share a question, so walk to a room not yet issued.
      const issued = new Set(
        Object.values<any>(g.encounters)
          .filter((e) => e.problem)
          .map((e) => e.questionRoom ?? e.id),
      );
      const st = g.floors
        .flatMap((f: any, floor: number) =>
          f.stations.map((s: any) => ({ ...s, floor })),
        )
        .filter(
          (s: any) =>
            g.encounters[s.encounter].state !== "consumed" &&
            !g.encounters[s.encounter].owner &&
            !issued.has(
              g.encounters[s.encounter].questionRoom ??
                g.encounters[s.encounter].id,
            ) &&
            Math.hypot(s.x - g.survivors[0].x, s.y - g.survivors[0].y) > 3,
        )[skip];
      if (!st) throw Error("No untouched station");
      Object.assign(g.survivors[0], { floor: st.floor, x: st.x, y: st.y });
      return st.encounter as string;
    }, skip);
    // Moving away releases the previous physical station on the real game frame.
    await expect
      .poll(() =>
        page.evaluate(
          () => (window as any).__deadAir.game.survivors[0].station,
        ),
      )
      .toBeUndefined();
    // A live question is generated by Claude; E opens once it is ready.
    await page.keyboard.press("e");
    // E either opens the terminal once Claude's question is ready, or grips a
    // partition at once. Stop waiting the moment it gripped.
    const state = async () =>
      (await page.evaluate(
        () => !!(window as any).__deadAir.game.survivors[0].grip,
      ))
        ? "grip"
        : (await page.locator("#terminal").isVisible())
          ? "terminal"
          : "";
    const outcome = await expect
      .poll(state, { timeout: 8000 })
      .not.toBe("")
      .then(state, () => "none");
    if (outcome === "terminal") {
      await expect(page.locator("#terminal")).toBeVisible();
      await expect
        .poll(() =>
          page.evaluate(
            (id) =>
              (window as any).__deadAir.game.encounters[id].problem?.contract
                .track,
            id,
          ),
        )
        .toBeTruthy();
      return id;
    }
    // Release a gripped partition and try the next station.
    if (outcome === "grip") await page.keyboard.press("e");
  }
}
const trackOf = (page: Page, id: string) =>
  page.evaluate(
    (id) =>
      (window as any).__deadAir.game.encounters[id].problem.contract.track,
    id,
  );
const consumed = (page: Page, id: string) =>
  page.evaluate(
    (id) => (window as any).__deadAir.game.encounters[id].state === "consumed",
    id,
  );
async function answer(page: Page, text: string) {
  await page.locator("#chat-input").fill(text);
  await page.locator("#chat-input").press("Enter");
}

test("practice completion, including a declared gap, rotates game questions across reload", async ({
  page,
}) => {
  // Five Claude-issued questions, a reload and a declared gap in one run.
  test.setTimeout(90_000);
  const relay = await mockClaudeStudy(page);
  await enterNativeGame(page);
  const practice = await page.evaluate(async () => {
    const d = (window as any).__deadAir,
      g = d.game,
      root = "/src/";
    const { eligible } = await import(
      /* @vite-ignore */ root + "curriculum.ts"
    );
    const { recordSpawn, spawnContract } = await import(
      /* @vite-ignore */ root + "topic-spawn.ts"
    );
    // Every question comes from Claude: a live run starts with none issued.
    g.study.profile = "live";
    for (const each of Object.values<any>(g.encounters)) delete each.problem;
    recordSpawn(
      g.study,
      eligible(d.roadmap, g.study),
      "synthetic-cooldown",
      g.time,
    );
    const c = spawnContract(d.roadmap, g.study);
    if (!c.practice) throw Error("Expected a variety practice contract");
    return c;
  });
  // Claude issues this first question under the practice contract.
  relay.forceNextContract(practice);
  await page.evaluate(() => {
    const d = (window as any).__deadAir,
      g = d.game,
      st = g.floors[0].stations[0],
      e = g.encounters[st.encounter];
    e.mode = "solo";
    e.owner = "human";
    // A question prepared before the cooldown was recorded is not this one.
    delete g.study.preparedQuestion;
    Object.assign(g.survivors[0], { floor: 0, x: st.x, y: st.y });
    return d.interact();
  });
  await expect(page.locator("#terminal")).toBeVisible();
  const id = await page.evaluate(
    () =>
      (window as any).__deadAir.game.floors[0].stations[0].encounter as string,
  );
  await expect.poll(() => trackOf(page, id).catch(() => undefined)).toBe("PY");
  expect(
    await page.evaluate(
      (id) =>
        (window as any).__deadAir.game.encounters[id].problem.contract.practice,
      id,
    ),
  ).toBe(true);
  relay.gap();
  await answer(page, "I do not know this part yet.");
  await expect.poll(() => consumed(page, id)).toBe(true);
  for (const track of ["PE", "PE", "PY"]) {
    const next = await openUntouched(page);
    await expect.poll(() => trackOf(page, next)).toBe(track);
    relay.solve();
    await answer(
      page,
      "Here is my complete reasoning for the scoped question.",
    );
    await expect.poll(() => consumed(page, next)).toBe(true);
  }
  const progress = await page.evaluate(() => {
    const s = (window as any).__deadAir.game.study;
    return {
      attempts: s.learner.attempts.map((a: any) => !!a.contract.practice),
      evidence: s.learner.evidence.length,
    };
  });
  // Only the two formal PE questions are learner attempts; practice earns none, and a
  // conversation with no knowledge report adds no learner evidence.
  expect(progress).toEqual({ attempts: [false, false], evidence: 0 });
  await flushNativeSave(page);
  await page.reload();
  await page.waitForFunction(() => !!(window as any).__deadAir);
  const last = await openUntouched(page);
  await expect.poll(() => trackOf(page, last)).toBe("PE");
});
